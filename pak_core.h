// pak_core.h — shared PAKP packer core, included by both pack.cpp (the CLI) and
// main.cpp (the GUI "Pack" button, PackExe). Keeping the 1709-byte decryptor
// machine code, the PAKP cipher, the LZSS compressor, and the two stub framings
// in ONE place means the two front ends cannot drift out of sync. The annotated
// stub source and build notes live in stub_src.c.
//
//   void unpack(const Ent* t, uint32_t n, const uint32_t* key);
//   Ent = {u64 dst; u64 src; u32 clen; u32 olen; u64 nonce;}  (32 bytes)
//
// At load the stub checks the PEB for a debugger and folds the result into the
// key, then PAKP-decrypts each blob in place (256-bit key in .pakp, per-section
// nonce) and LZSS-decompresses it (output-bounded) into its section.
