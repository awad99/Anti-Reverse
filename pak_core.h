// PAKP cipher — must match stub_src.c's unpack byte-for-byte. ChaCha-derived ARX
// keystream, 256-bit key + 64-bit nonce, 20 rounds, custom constants and state
// layout. XOR keystream, so encrypt == decrypt. x86 is little-endian, matching
// the stub's serialization.
static inline uint32_t pakp_rotl32(uint32_t v, int c) { return (v << c) | (v >> (32 - c)); }
static void pakp_xor(uint8_t* buf, uint32_t len, const uint32_t key[8], uint64_t nonce) {
    uint32_t st[16];
    for (int i = 0; i < 8; ++i) st[i] = key[i];
    st[8]  = 0x706b6170u; st[9]  = 0x6f727473u;   // "pakp" "stro"
    st[10] = 0x762e676eu; st[11] = 0x65786531u;   // "ng.v" "1exe"
    st[12] = 0; st[13] = 0;
    st[14] = (uint32_t)nonce; st[15] = (uint32_t)(nonce >> 32);
    uint32_t pos = 0;
    while (pos < len) {
        uint32_t x[16];
        for (int i = 0; i < 16; ++i) x[i] = st[i];
        for (int r = 0; r < 10; ++r) {
            #define PAKP_QR(a,b,c,d) a+=b; d^=a; d=pakp_rotl32(d,16); c+=d; b^=c; b=pakp_rotl32(b,12); \
                                     a+=b; d^=a; d=pakp_rotl32(d,8);  c+=d; b^=c; b=pakp_rotl32(b,7)
            PAKP_QR(x[0],x[4],x[8], x[12]); PAKP_QR(x[1],x[5],x[9], x[13]);
            PAKP_QR(x[2],x[6],x[10],x[14]); PAKP_QR(x[3],x[7],x[11],x[15]);
            PAKP_QR(x[0],x[5],x[10],x[15]); PAKP_QR(x[1],x[6],x[11],x[12]);
            PAKP_QR(x[2],x[7],x[8], x[13]); PAKP_QR(x[3],x[4],x[9], x[14]);
            #undef PAKP_QR
        }
        for (int i = 0; i < 16; ++i) x[i] += st[i];
        const uint8_t* ks = (const uint8_t*)x;
        for (int j = 0; j < 64 && pos < len; ++j) buf[pos++] ^= ks[j];
        if (++st[12] == 0) ++st[13];
    }
}

